"""AI Call 3: appeal letter from verified evidence only. PDF is written by code.

Requires the AI to quote the insurer's rejection wording verbatim as a block, then
post-checks that block against the rejection letter text. If the quoted insurer
wording does not appear in the letter, it is removed from the letter before the PDF
is built, and the event is recorded so the UI can flag it.
"""
from __future__ import annotations

import re
from typing import Any

from fpdf import FPDF

from pipeline.llm import LLMError, ask_json
from pipeline.verify import normalize

FOOTER = "Generated by ClaimCourt (demo). Review before sending. Not legal advice."

SYSTEM = """You write a formal health insurance claim appeal letter.

Source of truth:
- The policy text you are given is the ONLY authority for policy content. Do not cite laws,
  regulators, circulars, or any rule that is not present in the evidence. Do not invent
  clause numbers, page numbers, or policy quotes.
- The insurer's rejection wording is given in the evidence. Quote it EXACTLY as provided,
  in quotation marks, in a short block. Do not paraphrase it.

Letter requirements:
- Address it to the insurer's "Grievance Redressal Officer".
- Include a date placeholder.
- Use the policy and claim numbers given, or "[POLICY NUMBER]" and "[CLAIM NUMBER]" if missing.
- Include a section titled "The rejection we received" containing, inside quotation marks,
  the insurer's wording EXACTLY as provided (concatenate if several reasons are listed).
- Respond to each rejection reason point by point. Quote the policy clause EXACTLY as given
  in the evidence, and cite its page number. If a clause number is given in the evidence,
  cite it (for example "Clause 3.7A, page 4"). If no clause number is given, cite the page
  only; do not invent a clause number.
- Ask the insurer to reconsider and settle the claim.
- End with a polite closing.

Style and safety:
- Plain, polite English. No legal advice. No threats.
- Do not add reasons, quotes, clause numbers, pages, or facts that are not in the evidence.

Return JSON only, in this exact shape:
{"letter": "full letter text, paragraphs separated by blank lines",
 "insurer_quote_block": "the insurer's wording you quoted, verbatim"}
"""


class AppealError(ValueError):
    """User-safe message, shown directly in the UI."""


def build_evidence(
    reasons: list[dict[str, Any]],
    verdicts: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    """Keep only reasons whose quote passed verification and whose verdict supports an appeal.

    `clause` is carried through only when it verified. If the clause failed verification,
    it is set to None so the letter writer cites page only (and never a fake clause).
    """
    by_id = {r["id"]: r for r in reasons}
    evidence = []
    for v in verdicts:
        if not v.get("quote_verified") or v.get("verdict") != "rejection_contradicted":
            continue
        reason = by_id.get(v.get("reason_id"))
        if reason is None:
            continue
        clause = v.get("clause") if v.get("clause_verified") else None
        evidence.append({
            "reason_id": reason["id"],
            "insurer_words": reason["insurer_words"],
            "insurer_words_verified": bool(reason.get("insurer_words_verified")),
            "plain_english": reason["plain_english"],
            "policy_quote": v["policy_quote"],
            "page": v.get("quote_page") or v.get("page"),
            "clause": clause,
            "explanation": v.get("explanation", ""),
        })
    return evidence


def _sanitize(text: str) -> str:
    """fpdf2 core fonts are Latin-1 only. Replace common Unicode punctuation, drop the rest."""
    table = {
        "\u2018": "'", "\u2019": "'", "\u201c": '"', "\u201d": '"',
        "\u2013": "-", "\u2014": "-", "\u20b9": "Rs ", "\u2022": "-",
    }
    for src, dst in table.items():
        text = text.replace(src, dst)
    return text.encode("latin-1", "replace").decode("latin-1")


def _insurer_quote_in_letter(quote_block: str, letter_text: str) -> bool:
    """True if the quoted insurer wording appears in the rejection letter (normalized word run)."""
    needle = normalize(quote_block).split()
    if not needle:
        return False
    hay = normalize(letter_text).split()
    n = len(needle)
    first = needle[0]
    for i in range(len(hay) - n + 1):
        if hay[i] == first and hay[i:i + n] == needle:
            return True
    return False


def _strip_insurer_block(letter: str) -> str:
    """Remove the 'The rejection we received' section if its quoted block failed verification.

    Best-effort: matches a heading line and the following paragraph. If the heading is not
    present, the letter is returned unchanged (the caller flags this in insurer_quote_check).
    """
    pattern = re.compile(
        r"(?is)\n*the rejection we received[^\n]*\n+.*?(?=\n{2,}|\Z)",
    )
    return pattern.sub("\n\n", letter).strip()


def make_letter(evidence: list[dict[str, Any]], details: dict[str, str], letter_text: str) -> dict[str, Any]:
    """AI Call 3. Raises AppealError if no verified evidence, LLMError if the AI fails.

    Returns {'letter': str, 'insurer_quote_check': str, 'insurer_quote_block': str}.
    insurer_quote_check is one of: "verified", "not_found_removed", "not_provided".
    """
    if not evidence:
        raise AppealError(
            "No verified evidence supports an appeal, so no letter was written. "
            "See the next steps for your options."
        )
    payload = (
        f"INSURER: {details.get('insurer_name') or '[INSURER NAME]'}\n"
        f"POLICY NUMBER: {details.get('policy_number') or '[POLICY NUMBER]'}\n"
        f"CLAIM NUMBER: {details.get('claim_number') or '[CLAIM NUMBER]'}\n"
        f"INSURED NAME: {details.get('insured_name') or '[INSURED NAME]'}\n\n"
        "VERIFIED POLICY EVIDENCE (JSON):\n"
        f"{evidence}"
    )
    data = ask_json(SYSTEM, payload)
    letter = str(data.get("letter", "")).strip()
    if not letter:
        raise LLMError("AI returned an empty appeal letter. Try again.")

    insurer_block = str(data.get("insurer_quote_block", "")).strip()
    if not insurer_block:
        return {"letter": letter, "insurer_quote_check": "not_provided", "insurer_quote_block": ""}

    if _insurer_quote_in_letter(insurer_block, letter_text):
        return {"letter": letter, "insurer_quote_check": "verified", "insurer_quote_block": insurer_block}

    return {
        "letter": _strip_insurer_block(letter),
        "insurer_quote_check": "not_found_removed",
        "insurer_quote_block": insurer_block,
    }


def make_pdf_bytes(letter: str) -> bytes:
    """One-column PDF. Footer is drawn by fpdf2 on every page."""
    pdf = FPDF(format="A4")
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.set_margins(left=20, top=20, right=20)
    pdf.set_font("Helvetica", size=11)

    def footer() -> None:
        pdf.set_y(-15)
        pdf.set_font("Helvetica", size=8)
        pdf.cell(w=0, h=5, text=FOOTER, align="C")

    pdf.footer = footer
    pdf.add_page()

    for paragraph in _sanitize(letter).split("\n\n"):
        pdf.multi_cell(w=0, h=6, text=paragraph.strip(), new_x="LMARGIN", new_y="NEXT")
        pdf.ln(3)

    return bytes(pdf.output())


def generate_appeal(
    reasons: list[dict[str, Any]],
    verdicts: list[dict[str, Any]],
    details: dict[str, str] | None = None,
    letter_text: str = "",
) -> dict[str, Any]:
    """Return {'letter', 'pdf_bytes', 'checklist', 'evidence_count', 'insurer_quote_check'}.

    The letter is only produced when verified evidence supports at least one reason.
    If the PDF step itself fails, the letter is still returned and pdf_bytes is b"",
    so the UI can show the text without a broken download button.
    """
    evidence = build_evidence(reasons, verdicts)
    result = make_letter(evidence, details or {}, letter_text)
    try:
        pdf_bytes = make_pdf_bytes(result["letter"])
    except Exception:
        pdf_bytes = b""
    return {
        "letter": result["letter"],
        "pdf_bytes": pdf_bytes,
        "checklist": [],
        "evidence_count": len(evidence),
        "insurer_quote_check": result["insurer_quote_check"],
    }